    def cancel_process(self):
        # Actually terminate the child process, not just the thread signal.
        # Guard on _run_active: after a run ends the worker is deleteLater'd,
        # so calling into it would hit a deleted C++ object.
        if self._run_active and self.worker:
            self.update_output_log("Cancelling…")
            try:
                self.worker.cancel()
            except RuntimeError:
                pass

    def close_application(self):
        print("Closing application")
        self.close()

    def closeEvent(self, event):
        # Never let a running background QThread be destroyed while its OS
        # thread is alive — that qFatals QGIS. Stop/park threads first.
        self._shutdown_threads()
        super().closeEvent(event)

    def _shutdown_threads(self):
        """Stop background threads (inference + env build) so the dialog and
        its parentless QThreads can be torn down safely. Call this from the
        plugin's unload() too, before QGIS drops the dialog reference."""
        # Inference: cancelling terminates the child process, so the thread's
        # read loop returns quickly and the thread can be waited out.
        if self._run_active and self.worker is not None:
            try:
                self.worker.cancel()
            except (RuntimeError, AttributeError):
                pass
        self._reap_thread(self.thread, self.worker)
        # Env build: request cancel; network reads are timeout-bounded, but a
        # pip install mid-flight can't be interrupted, so it may get parked.
        if self._env_worker is not None:
            try:
                self._env_worker.cancel()
            except (RuntimeError, AttributeError):
                pass
        self._reap_thread(self._env_thread, self._env_worker)
        # Model download: network reads are timeout-bounded (30 s), so the
        # worker returns within a bounded time; park it if it doesn't.
        if self._dl_worker is not None:
            try:
                self._dl_worker.cancel()
            except (RuntimeError, AttributeError):
                pass
        self._reap_thread(self._dl_thread, self._dl_worker)
        # Environment probe: read-only, and every step is timeout-bounded
        # (30 s / 60 s subprocess timeouts, a bounded walk), so it can be
        # waited out. It is still reaped — a live QThread destroyed with
        # the dialog qFatals QGIS whatever the thread was doing.
        if self._probe_worker is not None:
            try:
                self._probe_worker.cancel()
            except (RuntimeError, AttributeError):
                pass
        self._reap_thread(self._probe_thread, self._probe_worker)

    def _reap_thread(self, thread, worker):
        """Quit + wait a bounded time for a QThread. If it is still running
        (e.g. pip mid-install), park it in _ALIVE_BG so it is never GC'd while
        running (which would qFatal); it self-evicts when it finishes."""
        if thread is None:
            return
        try:
            if not thread.isRunning():
                return
            thread.quit()
            if thread.wait(8000):
                return
            _ALIVE_BG.add(thread)
            if worker is not None:
                _ALIVE_BG.add(worker)

            def _evict(t=thread, w=worker):
                _ALIVE_BG.discard(t)
                _ALIVE_BG.discard(w)
            thread.finished.connect(_evict)
        except RuntimeError:
            pass

    def run_process(self):
        # Guard against re-entry: a second Run while one is live would reassign
        # self.thread and destroy a still-running QThread -> Qt qFatal aborts
        # the whole QGIS process. (This is what crashed QGIS.)
        if self._run_active:
            QtWidgets.QMessageBox.information(
                self, "WINMOL Analyzer",
                "A run is already in progress. Wait for it to finish, or press "
                "Cancel, before starting another.")
            return

        # Path to the Python script
        path_dirname = os.path.dirname(__file__)
        script_path = os.path.join(path_dirname, "winmol_run.py")

        # set chosen parameters
        self.set_selected_model()

        if not self.model_path:
            QtWidgets.QMessageBox.warning(self, "WINMOL Analyzer", "No model selected.")
            return
        if self.model_comboBox.currentText().strip() != "Custom" and not os.path.exists(self.model_path):
            if self._selected_entry is not None:
                # Registry model, not on disk yet: offer to fetch it now
                # (checksum-verified, on a background thread) and re-run.
                # This is the ONLY path that sets _dl_then_run.
                self._dl_then_run = True
                self._offer_model_download(self._selected_entry)
                return
            QtWidgets.QMessageBox.warning(
                self,
                "WINMOL Analyzer",
                f"Selected model file was not found:\n{self.model_path}\n\n"
                "Tip: fetch it on the Setup tab, or pick a Custom model file.",
            )
            return

        self.set_selected_process_type()
        self.set_path_from_line_edit()

        # Validate the input BEFORE launching the subprocess: an empty or
        # missing path otherwise surfaces as an opaque rasterio
        # "No such file or directory" deep in winmol_run.py.
        if not self.uav_path:
            QtWidgets.QMessageBox.warning(
                self, "WINMOL Analyzer",
                "No input GeoTiff selected. Pick a file, type a path, or "
                "choose a loaded raster layer.")
            return
        if not os.path.exists(self.uav_path):
            QtWidgets.QMessageBox.warning(
                self, "WINMOL Analyzer",
                f"Input GeoTiff was not found:\n{self.uav_path}")
            return
        # The stem map raster is always written; an empty output path crashes
        # the prediction phase. set_path_from_line_edit auto-derives it from the
        # input, so this only trips if that derivation somehow failed.
        if not self.stem_path or Path(self.stem_path).name == "":
            QtWidgets.QMessageBox.warning(
                self, "WINMOL Analyzer",
                "No output path is set and none could be derived from the "
                "input. Set an output stem map path.")
            return

        # check if uav image is loaded in qgis
        self.check_uav_input_exists(self.stem_path)

        if self.trees_path:
            # unload final gpkg layers
            self.check_uav_input_exists(self.trees_path)

            # unload *_new.gpkg layers too (fallback filename)
            p = Path(self.trees_path)
            alt = str(p.with_name(p.stem + "_new.gpkg"))
            self.check_uav_input_exists(alt)

        # Run winmol_run.py in the resolved compute environment. If it is
        # not usable, send the user to the Setup tab with the reason
        # already written out — no modal, and no launch.
        reason = setup_state.blocking_reason(self._env_snapshot(),
                                             self._busy_kind())
        if reason is not None or not self._env_ready():
            self._go_to_setup()
            self._set_status(reason or setup_state.TXT_BLOCK_NO_ENV)
            self._refresh_setup_state()
            return

        # The environment is usable — but is it using the right processor?
        # Asked HERE, once, because this is the last moment before the
        # user spends hours on something that takes minutes. Returns True
        # (proceed) for every state but an idle NVIDIA GPU, and for that
        # one too as soon as the user has answered it once.
        if not self._gpu_offer_pre_flight():
            return

        command = [
            self.python_exe,
            "-u",
            script_path,
            self.model_path,
            self.uav_path,
            self.stem_path,
            self.trees_path,
            self.process_type,
        ]

        # Switch to the log tab in the QTabWidget (by widget, never by
        # index — the Setup page sits between Detection and Log now)
        self._go_to_log()

        # clear the output log
        self.output_log.clear()

        self.update_output_log("Starting the process...")

        # for debugging run subprocess directly
        # import subprocess
        # process = subprocess.run(
        #     command,
        #     capture_output=True,
        #     text=True
        # )
        # print(process.stdout)
        # print(process.stderr)
        # self.update_output_log(process.stdout)
        # self.update_output_log(process.stderr)

        # Run this part for responsive GUI
        print("Starting the process...")
        try:
            self.thread = QThread()
            # Point the child's batch-size autotune cache at WINMOL's managed
            # state, so it is created, found and deleted with the environment
            # rather than in a HOME the QGIS/Docker user may not own.
            env_extra = {
                "WINMOL_AUTOTUNE_CACHE":
                    installer.autotune_cache_location(self._plugin_dir()),
            }
            # The run command is five positional arguments; the environment is
            # the only channel that carries a config value to the child.
            env_extra.update(self._batch_override_env())
            self.worker = Worker(command, env_extra=env_extra)
            self.worker.moveToThread(self.thread)
            self.worker.progress_signal.connect(self.update_progress)
            self.thread.started.connect(self.worker.run_process)
            # layers load ONLY on success; failures surface in the log/dialog
            self.worker.succeeded.connect(self.load_layers_to_session)
            self.worker.error.connect(self.handle_process_error)
            self.worker.finished.connect(self.thread.quit)
            self.worker.finished.connect(self.worker.deleteLater)
            self.thread.finished.connect(self.thread.deleteLater)
            self.thread.finished.connect(self._on_run_finished)
            self.worker.update_signal.connect(self.update_output_log)
            # Mark active + lock Run and every Setup button BEFORE
            # starting, so a second click can't reassign self.thread (abort) or
            # start a competing env build.
            self._run_active = True
            self._show_run_progress(True)
            self._set_busy_ui(True)
            self._set_status(RUN_STATUS)
            self.thread.start()
        # catch out of memory error
        except MemoryError:
            self._run_active = False
            self._show_run_progress(False)
            try:
                self.run_button.setEnabled(True)
            except Exception:
                pass
            self.worker.update_signal.disconnect(self.update_output_log)
            self.update_output_log(
                "The operation ran out of memory. "
                "Please free up some memory and "
                "try again."
            )
            self.check_swap_memory()

    def update_output_log(self, text):
        # Update your QPlainTextEdit with the output
        self.output_log.appendPlainText(text)

    def handle_process_error(self, message):
        """Show a failure instead of silently loading empty/absent layers."""
        self.update_output_log(message)
        try:
            QtWidgets.QMessageBox.warning(self, "WINMOL Analyzer", message)
        except Exception:
            pass

    def _on_run_finished(self):
        """Runs on thread.finished (success OR failure): clear the active flag
        so the next run can safely build a fresh thread, and re-enable the UI.
        Offers Export if the run produced outputs on disk."""
        self._run_active = False
        self._show_run_progress(False)
        # One repaint decides what comes back: the interlock knows about
        # an env job or a download still in flight, which the old
        # hand-rolled tuple did not.
        self._refresh_setup_state()
        produced = any(os.path.exists(p) for p in self._last_outputs)
        self._set_export_enabled(produced)
        if produced and self._last_output_is_temp:
            self.update_output_log(
                "Outputs were written to a temp folder. Use 'Export…' to save "
                "them to a permanent location.")

    def _set_export_enabled(self, on):
        btn = getattr(self, "export_button", None)
        if btn is not None:
            try:
                btn.setEnabled(bool(on))
            except Exception:
                pass

    def export_results(self):
        """Copy the last run's outputs (stem map + any gpkg) to a folder the
        user chooses. Lets runs default to a temp dir yet still be saved."""
        import shutil
        outputs = [p for p in self._last_outputs if os.path.exists(p)]
        if not outputs:
            QtWidgets.QMessageBox.information(
                self, "WINMOL Analyzer",
                "No results to export yet. Run an analysis first.")
            return
        target_dir = QFileDialog.getExistingDirectory(
            self, "Export results to folder", "")
        if not target_dir:
            return
        copied = []
        for src in outputs:
            try:
                dst = os.path.join(target_dir, os.path.basename(src))
                shutil.copy2(src, dst)
                copied.append(dst)
                # bring along a sidecar stats file if the raster has one
                sidecar = src + ".aux.xml"
                if os.path.exists(sidecar):
                    shutil.copy2(sidecar, dst + ".aux.xml")
            except Exception as exc:
                self.update_output_log(f"Export failed for {src}: {exc}")
        if copied:
            self.update_output_log("Exported:\n" + "\n".join(copied))
            QtWidgets.QMessageBox.information(
                self, "WINMOL Analyzer",
                f"Exported {len(copied)} file(s) to:\n{target_dir}")

